"""
GT (Ground Truth) Dataset Builder

Builds YAMNet-compatible training datasets from rendered audio.

For each render that has per-source sidecars (generated by the renderer),
this module:
  1. Loads each source's isolated room-processed mic signals (partial sidecar)
  2. Adds the ambient background slice for that time window
  3. Chunks the combined signal into 0.96-second YAMNet windows (50% hop)
  4. Saves as 16 kHz mono WAV + manifest CSV

The resulting dataset has:
  - Realistic room acoustics (RIR from pyroomacoustics)
  - Correct single-mic directional coloring
  - Real ambient background (not silence)
  - Zero label contamination (one labeled source per clip)
  - train / val / test fold assignment with no leakage across source events

Dataset structure
-----------------
outputs/gt_datasets/<dataset_name>/
    audio/
        <label>/
            src00_clip0000.wav
            ...
        background/
            bg_clip0000.wav
            ...
    manifest.csv          # wav_path, label, source_idx, scene, fold
    dataset_info.json     # summary statistics
"""

import streamlit as st
import numpy as np
import json
import os
import re
import pandas as pd
from pathlib import Path
from datetime import datetime
import soundfile as sf
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import librosa
import librosa.display


class GTDatasetBuilder:
    """Builds YAMNet training datasets from rendered audio with GT sidecars."""

    YAMNET_WINDOW_S = 3.0     # training window — 3 × 0.96s YAMNet patches
    YAMNET_HOP_S    = 1.5     # 50% overlap
    SAMPLE_RATE     = 16000
    RIR_TAIL_S      = 1.5     # buffer past audio_active_samples to keep RIR tail

    def __init__(self, renders_dir, output_dir):
        self.renders_dir = Path(renders_dir)
        self.output_dir  = Path(output_dir) / 'gt_datasets'
        self.output_dir.mkdir(parents=True, exist_ok=True)

        self.yamnet_window    = int(self.YAMNET_WINDOW_S * self.SAMPLE_RATE)  # 48 000
        self.yamnet_hop       = int(self.YAMNET_HOP_S    * self.SAMPLE_RATE)  # 24 000
        self.rir_tail_samples = int(self.RIR_TAIL_S      * self.SAMPLE_RATE)  # 24 000

    @staticmethod
    def _sanitize_label(label: str) -> str:
        return re.sub(r'[^\w\-]', '_', str(label))

    def _resolve_manifest_wav_path(self, dataset_path: Path, wav_path: str, label: str = '') -> Path:
        """Resolve manifest wav paths when legacy absolute paths no longer exist."""
        raw = Path(str(wav_path))
        if raw.exists():
            return raw

        audio_root = dataset_path / 'audio'
        candidates: list[Path] = []
        if not raw.is_absolute():
            candidates.append(dataset_path / raw)
            candidates.append(audio_root / raw)

        if label:
            candidates.append(audio_root / self._sanitize_label(label) / raw.name)
            candidates.append(audio_root / str(label) / raw.name)
        candidates.append(audio_root / raw.name)

        for candidate in candidates:
            if candidate.exists():
                return candidate

        matches = list(audio_root.rglob(raw.name)) if audio_root.exists() else []
        if matches:
            return matches[0]

        return raw

    # ── Render / dataset discovery ────────────────────────────────────────────

    def _find_gt_renders(self):
        """Return renders that have source_sidecars and at least one sidecar file."""
        renders = []
        for json_path in sorted(self.renders_dir.glob('*.json')):
            try:
                with open(json_path) as f:
                    meta = json.load(f)
            except Exception:
                continue
            if not meta.get('source_sidecars'):
                continue
            raw_path = json_path.with_suffix('.raw')
            if not raw_path.exists():
                continue
            if not any(os.path.exists(s['sidecar_path']) for s in meta['source_sidecars']):
                continue
            renders.append({
                'meta':     meta,
                'raw_path': str(raw_path),
                'filename': json_path.stem,
                'mtime':    os.path.getmtime(json_path),
            })
        renders.sort(key=lambda r: r['mtime'], reverse=True)
        return renders

    def _list_datasets(self):
        """Return info dicts for existing GT datasets."""
        datasets = []
        for d in sorted(self.output_dir.iterdir()):
            manifest = d / 'manifest.csv'
            if not (d.is_dir() and manifest.exists()):
                continue
            try:
                df = pd.read_csv(manifest)
                datasets.append({
                    'name':    d.name,
                    'path':    str(d),
                    'n_clips': len(df),
                    'labels':  sorted(df['label'].unique().tolist()),
                    'mtime':   os.path.getmtime(manifest),
                })
            except Exception:
                pass
        datasets.sort(key=lambda x: x['mtime'], reverse=True)
        return datasets

    # ── Core dataset builder ──────────────────────────────────────────────────

    def build_from_render(self, meta, dataset_name,
                          mic_channel='random',
                          include_background=True,
                          min_clip_occupancy=0.5,
                          window_s=3.0,
                          min_rms=0.01):
        """
        Build a labeled clip dataset from one render.

        Parameters
        ----------
        meta               : render metadata dict (from the .json sidecar)
        dataset_name       : output folder name under gt_datasets/
        mic_channel        : int 0-3 (fixed) or 'random' (randomised per source)
        include_background : extract ambient-only clips from gaps as 'background'
        min_clip_occupancy : minimum fraction of window a source must fill
        window_s           : clip window length in seconds (default 3.0)
        min_rms            : minimum RMS threshold — clips below this are skipped
        """
        dataset_path = self.output_dir / dataset_name
        audio_dir    = dataset_path / 'audio'
        audio_dir.mkdir(parents=True, exist_ok=True)

        clips         = []
        n_samples     = int(meta['duration'] * self.SAMPLE_RATE)

        # Override window/hop for this build run
        win = int(window_s * self.SAMPLE_RATE)
        hop = win // 2

        # ── Load ambient sidecar mmap ─────────────────────────────────────────
        amb_path     = meta.get('ambient_sidecar_path', '')
        ambient_mmap = None
        if amb_path and os.path.exists(amb_path):
            amb_frames = os.path.getsize(amb_path) // (4 * 4)   # float32, 4 ch
            if amb_frames > 0:
                ambient_mmap = np.memmap(amb_path, dtype=np.float32, mode='r',
                                         shape=(4, amb_frames))

        status   = st.empty()
        progress = st.progress(0)
        sidecars = meta['source_sidecars']
        n_src    = len(sidecars)

        # ── Process each directional source ───────────────────────────────────
        for i_src, src_info in enumerate(sidecars):
            label = src_info['label']
            status.text(f"Source {i_src + 1}/{n_src}: {label} …")
            progress.progress(i_src / max(n_src, 1))

            sidecar_path = src_info['sidecar_path']
            if not os.path.exists(sidecar_path):
                st.warning(f"Missing sidecar: {sidecar_path}")
                continue

            n_frames = src_info['n_frames']
            try:
                raw = np.fromfile(sidecar_path, dtype=np.float32)
                if raw.size != 4 * n_frames:
                    st.warning(f"Sidecar size mismatch for {label}, skipping")
                    continue
                partial = raw.reshape(4, n_frames)
            except Exception as e:
                st.warning(f"Could not load {sidecar_path}: {e}")
                continue

            # Pick mic channel
            ch = np.random.randint(0, 4) if mic_channel == 'random' else int(mic_channel)

            # Source audio = room-processed partial for chosen mic
            src_audio = partial[ch].copy().astype(np.float32)
            del partial

            # Trim to actual content + RIR tail — avoids chunking silent padding
            active_samp = src_info.get('audio_active_samples', len(src_audio))
            trim_end    = min(active_samp + self.rir_tail_samples, len(src_audio))
            src_audio   = src_audio[:trim_end]

            # Add ambient background for this time window
            if ambient_mmap is not None:
                a_start  = src_info['start_sample']
                a_end    = min(src_info['end_sample'], ambient_mmap.shape[1])
                amb_len  = min(a_end - a_start, len(src_audio))
                if amb_len > 0:
                    src_audio[:amb_len] += ambient_mmap[ch, a_start:a_start + amb_len]

            # Skip sources far too short (< min_clip_occupancy of one window)
            min_frames = int(min_clip_occupancy * win)
            if len(src_audio) < min_frames:
                continue

            # Save clips
            label_dir = audio_dir / re.sub(r'[^\w\-]', '_', label)
            label_dir.mkdir(exist_ok=True)

            new_clips = self._chunk_and_save(
                src_audio, label, label_dir,
                source_idx=src_info['source_idx'],
                scene=meta['scene_name'],
                win=win, hop=hop, min_rms=min_rms,
            )
            clips.extend(new_clips)

        # ── Background class ──────────────────────────────────────────────────
        if include_background and ambient_mmap is not None:
            status.text("Extracting background clips …")
            bg_clips = self._extract_background_clips(
                ambient_mmap, sidecars,
                audio_dir / 'background',
                n_samples, meta['scene_name'],
                win=win, hop=hop, min_rms=min_rms,
            )
            clips.extend(bg_clips)

        if ambient_mmap is not None:
            del ambient_mmap

        # ── Save manifest and summary ─────────────────────────────────────────
        manifest_path = self._save_manifest(clips, dataset_path)

        progress.progress(1.0)
        status.text("✅ Done!")

        return dataset_path, clips

    def _chunk_and_save(self, audio, label, output_dir, source_idx, scene,
                        win=None, hop=None, min_rms=0.01):
        """Chunk a float32 audio array into windows and save as WAVs.

        The sidecar data is unnormalized RIR output, so absolute RMS is
        meaningless as an energy gate.  Instead we gate on peak amplitude
        (> 1e-5) to skip zero / near-zero clips only.  _save_clip does
        peak-normalisation before writing so output WAVs are always
        correctly scaled regardless of the raw amplitude.
        """
        if win is None: win = self.yamnet_window
        if hop is None: hop = self.yamnet_hop
        clips    = []
        n        = len(audio)
        clip_idx = 0

        if n < win:
            # Single zero-padded clip
            padded       = np.zeros(win, dtype=np.float32)
            padded[:n]   = audio
            if np.abs(padded).max() > 1e-5:
                wav_name = f"src{source_idx:02d}_clip{clip_idx:04d}.wav"
                wav_path = output_dir / wav_name
                self._save_clip(padded, wav_path)
                clips.append({'wav_path': str(wav_path), 'label': label,
                              'source_idx': source_idx, 'scene': scene})
        else:
            start = 0
            while start + win <= n:
                chunk = audio[start:start + win].copy()
                if np.abs(chunk).max() > 1e-5:
                    wav_name = f"src{source_idx:02d}_clip{clip_idx:04d}.wav"
                    wav_path = output_dir / wav_name
                    self._save_clip(chunk, wav_path)
                    clips.append({'wav_path': str(wav_path), 'label': label,
                                  'source_idx': source_idx, 'scene': scene})
                    clip_idx += 1
                start += hop

        return clips

    def _extract_background_clips(self, ambient_mmap, source_sidecars,
                                   bg_dir, total_frames, scene_name,
                                   win=None, hop=None, min_rms=0.01):
        """Extract ambient-only clips from the gaps between source events."""
        if win is None: win = self.yamnet_window
        if hop is None: hop = self.yamnet_hop
        bg_dir.mkdir(exist_ok=True)
        clips = []

        # Find gap intervals (regions with no active directional source)
        occupied = sorted((s['start_sample'], s['end_sample'])
                          for s in source_sidecars)
        gaps, prev_end = [], 0
        for s_start, s_end in occupied:
            if s_start > prev_end + win:
                gaps.append((prev_end, s_start))
            prev_end = max(prev_end, s_end)
        if total_frames > prev_end + win:
            gaps.append((prev_end, total_frames))

        amb_frames = ambient_mmap.shape[1]
        clip_idx   = 0
        for gap_start, gap_end in gaps:
            ch  = np.random.randint(0, 4)
            pos = gap_start
            while pos + win <= min(gap_end, amb_frames):
                chunk = ambient_mmap[ch, pos:pos + win].copy().astype(np.float32)
                if np.abs(chunk).max() > 1e-5:
                    wav_name = f"bg_clip{clip_idx:04d}.wav"
                    wav_path = bg_dir / wav_name
                    self._save_clip(chunk, wav_path)
                    clips.append({'wav_path': str(wav_path), 'label': 'background',
                                   'source_idx': -1, 'scene': scene_name})
                    clip_idx += 1
                pos += hop

        return clips

    def _save_clip(self, audio: np.ndarray, path: Path):
        """Peak-normalise and write as 16-bit PCM WAV."""
        audio   = audio.astype(np.float32)
        max_val = np.abs(audio).max()
        if max_val > 0:
            audio = audio / max_val * 0.9
        sf.write(str(path), audio, self.SAMPLE_RATE, subtype='PCM_16')

    def _save_manifest(self, clips, dataset_path):
        """Save manifest.csv + dataset_info.json with stratified fold assignment."""
        if not clips:
            return None

        df = pd.DataFrame(clips)
        df['fold'] = 'train'

        # Assign folds per (label, source_idx) group — no intra-source leakage.
        # Special case: background clips all share source_idx=-1 (a single sentinel
        # value), so source-level splitting would put every clip in the same fold.
        # For any label whose clips share a single source_idx, fall back to
        # clip-level splitting (70 / 15 / 15).
        rng = np.random.default_rng(seed=42)
        for label in df['label'].unique():
            mask       = df['label'] == label
            source_ids = df.loc[mask, 'source_idx'].unique()
            n_sources  = len(source_ids)

            if n_sources <= 1:
                # Clip-level split: treat every clip as its own unit
                clip_indices = rng.permutation(df.index[mask].tolist())
                n       = len(clip_indices)
                n_val   = max(1, int(round(n * 0.15)))
                n_test  = max(1, int(round(n * 0.10)))
                df.loc[clip_indices[:n_val],            'fold'] = 'val'
                df.loc[clip_indices[n_val:n_val+n_test],'fold'] = 'test'
                # remainder stays 'train'
            else:
                # Source-level split — preserves no-leakage guarantee
                source_ids = rng.permutation(source_ids)
                n      = n_sources
                n_val  = max(1, int(round(n * 0.10)))
                n_test = max(1, int(round(n * 0.10)))
                val_ids  = set(source_ids[:n_val])
                test_ids = set(source_ids[n_val:n_val + n_test])
                df.loc[mask & df['source_idx'].isin(val_ids),  'fold'] = 'val'
                df.loc[mask & df['source_idx'].isin(test_ids), 'fold'] = 'test'

        manifest_path = dataset_path / 'manifest.csv'
        df.to_csv(manifest_path, index=False)

        summary = {
            'created_at':       datetime.now().isoformat(),
            'n_clips':          int(len(df)),
            'labels':           sorted(df['label'].unique().tolist()),
            'clips_per_label':  df['label'].value_counts().to_dict(),
            'fold_counts':      df['fold'].value_counts().to_dict(),
            'sample_rate':      self.SAMPLE_RATE,
            'window_s':         self.YAMNET_WINDOW_S,
            'hop_s':            self.YAMNET_HOP_S,
        }
        with open(dataset_path / 'dataset_info.json', 'w') as f:
            json.dump(summary, f, indent=2)

        return manifest_path

    # ── Streamlit UI ──────────────────────────────────────────────────────────

    def render(self):
        st.subheader("🏷️ Ground Truth Dataset Builder")
        st.markdown(
            "Extracts labeled training clips from rendered audio. "
            "Each clip = one source's **room-processed signal** (via pyroomacoustics) "
            "+ **ambient background** on a **single mic channel** — "
            "exactly the distribution the model sees at inference time."
        )

        tab_build, tab_browse = st.tabs(["🔨 Build Dataset", "📂 Browse Datasets"])
        with tab_build:
            self._render_build_tab()
        with tab_browse:
            self._render_browse_tab()

    # ── Build tab ─────────────────────────────────────────────────────────────

    def _render_build_tab(self):
        gt_renders = self._find_gt_renders()

        # ── Show renders that are silently skipped so the user knows why ──────
        all_render_jsons = sorted(self.renders_dir.glob('*.json'))
        skipped = []
        for jp in all_render_jsons:
            try:
                meta = json.load(open(jp))
            except Exception:
                continue
            sidecars = meta.get('source_sidecars', [])
            if not sidecars:
                skipped.append((jp.stem, 'no directional sources rendered'))
            elif not any(os.path.exists(s['sidecar_path']) for s in sidecars):
                skipped.append((jp.stem, 'sidecar .f32 files missing from disk'))
        skipped_names = {s[0] for s in skipped}
        # Only show skipped if they are not already in gt_renders
        valid_names = {r['filename'].replace('.json','') for r in gt_renders}
        skipped = [(n, r) for n, r in skipped if n not in valid_names]

        if skipped:
            with st.expander(f"⚠️ {len(skipped)} render(s) not usable for GT building", expanded=True):
                for name, reason in skipped:
                    st.markdown(f"- **`{name}`** — {reason}")
                st.caption(
                    "To fix: open **🔊 Audio Renderer**, load the scene, "
                    "add at least one directional source, and re-render. "
                    "The renderer writes per-source `.f32` sidecar files only "
                    "when directional sources are present."
                )

        if not gt_renders:
            st.warning(
                "No renders with GT sidecars found. "
                "Re-render a scene — the renderer saves per-source `.f32` "
                "sidecar files alongside the `.raw` output automatically "
                "when the scene has directional sources."
            )
            return

        # ── Render selector ───────────────────────────────────────────────────
        render_options = {r['filename']: r for r in gt_renders}
        selected_name  = st.selectbox(
            "Select render",
            list(render_options.keys()),
        )
        sel  = render_options[selected_name]
        meta = sel['meta']

        sidecars = meta['source_sidecars']

        # Scene summary
        st.markdown(
            f"**Scene:** `{meta['scene_name']}`  |  "
            f"**Duration:** {meta['duration']} s  |  "
            f"**Directional sources:** {len(sidecars)}"
        )

        # Source inventory and sidecar status
        col_src, col_status = st.columns(2)
        with col_src:
            st.markdown("**Sources:**")
            label_counts: dict = {}
            for s in sidecars:
                label_counts[s['label']] = label_counts.get(s['label'], 0) + 1
            for lbl, cnt in label_counts.items():
                st.markdown(f"- `{lbl}` × {cnt}")

        with col_status:
            st.markdown("**Sidecar files on disk:**")
            amb_ok = bool(meta.get('ambient_sidecar_path') and
                          os.path.exists(meta['ambient_sidecar_path']))
            st.markdown(f"- Ambient track: {'✅' if amb_ok else '❌ missing'}")
            for s in sidecars:
                ok = os.path.exists(s['sidecar_path'])
                st.markdown(
                    f"- `{s['label']}` (src {s['source_idx']:02d}): "
                    f"{'✅' if ok else '❌ missing'}"
                )

        st.markdown("---")

        # ── Build options ─────────────────────────────────────────────────────
        col1, col2, col3 = st.columns(3)
        with col1:
            default_name = (
                f"gt_{re.sub(chr(32), '_', meta['scene_name'])}_"
                f"{datetime.now().strftime('%Y%m%d')}"
            )
            dataset_name = st.text_input("Dataset name", value=default_name)

        with col2:
            mic_options = {
                'Random (varies per source)': 'random',
                'Mic 0 — Left':  0,
                'Mic 1 — Back':  1,
                'Mic 2 — Right': 2,
                'Mic 3 — Front': 3,
            }
            mic_label   = st.selectbox("Mic channel", list(mic_options.keys()))
            mic_channel = mic_options[mic_label]

        with col3:
            include_bg = st.checkbox(
                "Include background class", value=True,
                help="Extract ambient-only clips from time gaps between sources"
            )

        col4, col5 = st.columns(2)
        with col4:
            window_s = st.select_slider(
                "Clip window (seconds)",
                options=[0.96, 1.5, 2.0, 3.0, 5.0],
                value=3.0,
                help="3s recommended: captures full vocalisations and gives YAMNet 3 overlapping patches"
            )
        with col5:
            st.info(
                "💡 **Energy gating**: clips are kept if peak amplitude > 1e-5 "
                "(skips only zero/silent clips). Sidecar data is unnormalized RIR output "
                "so a fixed dBFS threshold would incorrectly reject real audio."
            )
            min_rms = 0.0  # not used for source clips; kept for API compat
            min_rms_db = -80  # display only

        # Clip count estimate
        n_est = sum(
            max(1, int((s['end_time'] - s['start_time']) / (window_s * 0.5)))
            for s in sidecars
        )
        st.caption(f"Estimated clips from directional sources: ~{n_est}  |  window={window_s}s  |  gate={min_rms_db} dBFS")

        # ── Build button ──────────────────────────────────────────────────────
        if st.button("🔨 Build GT Dataset", type="primary"):
            if not dataset_name.strip():
                st.error("Please enter a dataset name.")
                return
            with st.spinner("Building dataset …"):
                try:
                    ds_path, clips = self.build_from_render(
                        meta, dataset_name.strip(),
                        mic_channel=mic_channel,
                        include_background=include_bg,
                        window_s=window_s,
                        min_rms=min_rms,
                    )
                    st.success(f"✅ Built **{len(clips)}** clips → `{ds_path}`")
                    counts = pd.Series([c['label'] for c in clips]).value_counts()
                    st.dataframe(
                        counts.rename('clips').reset_index().rename(
                            columns={'index': 'label'}
                        )
                    )
                except Exception as e:
                    st.error(f"Error: {e}")
                    import traceback
                    st.code(traceback.format_exc())

    # ── Browse tab ────────────────────────────────────────────────────────────

    def _render_browse_tab(self):
        datasets = self._list_datasets()
        if not datasets:
            st.info("No GT datasets yet. Use the Build tab to create one.")
            return

        for ds in datasets:
            header = (
                f"📁 **{ds['name']}**  —  {ds['n_clips']} clips, "
                f"{len(ds['labels'])} classes: "
                + ", ".join(f"`{l}`" for l in ds['labels'])
            )
            with st.expander(header, expanded=False):
                self._render_dataset_detail(ds)

    def _render_dataset_detail(self, ds):
        dataset_path = Path(ds['path'])
        manifest_path = dataset_path / 'manifest.csv'
        df = pd.read_csv(manifest_path)

        # ── Summary metrics ────────────────────────────────────────────────────
        col1, col2, col3, col4 = st.columns(4)
        col1.metric("Total clips", len(df))
        col2.metric("Classes", df['label'].nunique())
        col3.metric("Train",  int((df['fold'] == 'train').sum()))
        col4.metric("Val + Test", int((df['fold'] != 'train').sum()))

        # ── Class distribution bar chart ───────────────────────────────────────
        counts = df['label'].value_counts()
        fig, ax = plt.subplots(figsize=(max(5, len(counts) * 0.9), 3))
        counts.plot(kind='bar', ax=ax, color='steelblue', edgecolor='white')
        ax.set_title("Clips per class")
        ax.set_ylabel("Count")
        ax.set_xlabel("")
        plt.xticks(rotation=40, ha='right')
        plt.tight_layout()
        st.pyplot(fig)
        plt.close(fig)

        # ── Per-class × fold breakdown ─────────────────────────────────────────
        fold_df = (
            df.groupby(['label', 'fold']).size()
            .unstack(fill_value=0)
            .reindex(columns=['train', 'val', 'test'], fill_value=0)
        )
        st.dataframe(fold_df)

        # ── Sample player ──────────────────────────────────────────────────────
        st.markdown("---")
        st.markdown("**🎧 Sample clips**")
        labels_avail = sorted(df['label'].unique().tolist())
        sel_label = st.selectbox(
            "Class to preview",
            labels_avail,
            key=f"preview_label_{ds['name']}"
        )

        label_df = df[df['label'] == sel_label]
        label_clips = [
            str(self._resolve_manifest_wav_path(dataset_path, row['wav_path'], row.get('label', '')))
            for _, row in label_df.iterrows()
        ]
        n_show      = min(3, len(label_clips))
        rng         = np.random.default_rng()
        sample_paths = rng.choice(label_clips, n_show, replace=False).tolist()

        audio_cols = st.columns(n_show) if n_show > 1 else [st.container()]
        for col, wav_path in zip(audio_cols, sample_paths):
            with col:
                if not os.path.exists(wav_path):
                    st.caption(f"Missing: {wav_path}")
                    continue
                st.caption(os.path.basename(wav_path))
                audio_data, sr = sf.read(wav_path, dtype='float32')
                st.audio(audio_data, sample_rate=sr)

        # ── Mel spectrogram of first sample ───────────────────────────────────
        if sample_paths and os.path.exists(sample_paths[0]):
            st.markdown("**Mel spectrogram — first sample**")
            try:
                audio_data, sr = sf.read(sample_paths[0], dtype='float32')
                mel    = librosa.feature.melspectrogram(
                    y=audio_data, sr=sr, n_mels=64, fmax=8000
                )
                mel_db = librosa.power_to_db(mel, ref=np.max)
                fig2, ax2 = plt.subplots(figsize=(8, 3))
                img = librosa.display.specshow(
                    mel_db, sr=sr, x_axis='time', y_axis='mel', ax=ax2
                )
                ax2.set_title(
                    f"{sel_label} — {os.path.basename(sample_paths[0])}"
                )
                plt.colorbar(img, ax=ax2, format='%+2.0f dB')
                plt.tight_layout()
                st.pyplot(fig2)
                plt.close(fig2)
            except Exception as e:
                st.caption(f"Could not render spectrogram: {e}")
